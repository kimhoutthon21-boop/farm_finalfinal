function t(string $text): string {
    return current_language() === 'km' ? (translations()[$text] ?? $text) : $text;
}

function current_page_target(): string {
    $uri = (string)($_SERVER['REQUEST_URI'] ?? '');
    $path = parse_url($uri, PHP_URL_PATH) ?: '';
    $base = parse_url(BASE_URL, PHP_URL_PATH) ?: '';
    if ($base !== '' && str_starts_with($path, $base . '/')) $path = substr($path, strlen($base) + 1);
    else $path = ltrim($path, '/');
    $query = parse_url($uri, PHP_URL_QUERY);
    $target = $path . ($query !== null && $query !== '' ? '?' . $query : '');
    return preg_match('#^[A-Za-z0-9_\-/\.]+(\?[A-Za-z0-9_\-=&%\.\[\]+]*)?$#', $target) && !str_contains($target, '..') && !str_contains($target, '//')
        ? $target : 'dashboard.php';
}

function language_switcher(): string {
    $current = current_language();
    $return = e(current_page_target());
    $html = '<form class="language-switch" method="post" action="' . e(url('actions/language.php')) . '" aria-label="' . e(t('Switch language')) . '">';
    $html .= csrf_field() . '<input type="hidden" name="return" value="' . $return . '">';
    $html .= '<input type="hidden" name="language" value="' . $current . '">';
    $html .= '<label class="language-toggle" for="language-toggle" aria-label="' . e(t('Switch language')) . '">';
    $html .= '<input id="language-toggle" type="checkbox" data-language-toggle' . ($current === 'km' ? ' checked' : '') . '>';
    $html .= '<span>EN</span><span>ខ្មែរ</span></label>';
    return $html . '</form>';
}
